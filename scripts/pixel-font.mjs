export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Width in SVG units of `text` at `scale`, including inter-glyph gaps. */
export function textWidth(text, scale, gap = 1) {
  const n = [...String(text)].length;
  return n ? n * (GLYPH_W + gap) * scale - gap * scale : 0;
}

/**
 * `text` as a run of <rect>s, top-left at (x, y).
 * Unknown characters render as a blank cell rather than throwing — a stat bar
 * that loses one glyph is still readable; one that fails to build is not.
 */
export function textRects(text, x, y, scale, fill, { gap = 1, opacity } = {}) {
  const out = [];
  let cx = x;
  for (const ch of String(text).toUpperCase()) {
    const rows = G[ch] ?? G[' '];
    for (let r = 0; r < rows.length; r++) {
      let c = 0;
      while (c < GLYPH_W) {
        if (rows[r][c] !== '#') { c++; continue; }
        // merge horizontally adjacent pixels into one rect — a third of the
        // node count, and identical output
        let run = 1;
        while (c + run < GLYPH_W && rows[r][c + run] === '#') run++;
        out.push(
          `<rect x="${cx + c * scale}" y="${y + r * scale}" ` +
          `width="${run * scale}" height="${scale}" fill="${fill}"` +
          `${opacity != null ? ` opacity="${opacity}"` : ''}/>`,
        );
        c += run;
      }
    }
    cx += (GLYPH_W + gap) * scale;
  }
  return out.join('');
}
